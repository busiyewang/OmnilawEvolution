"""Code templates used by the offline TemplateExecutor.

Each method maps to a block of source plus a step in ``dedup``. The executor
renders a complete replacement for the target module from the methods a
proposal selected. This stands in for a coding model so that the loop runs
without a paid API; it is not model-generated code, and reports say so.
"""
from __future__ import annotations

HEADER = '''"""Collector deduplication module (evolution target).

Contract used by the collector pipeline and the evaluator:

    dedup(items) -> list of {{"id": str, "duplicate_of": str | None, "reason": str}}

One decision per input item, in input order. ``duplicate_of`` must name an
earlier item that was kept.

Generated by omnilaw-evolution ({generator}) for run {run_id}, variant {variant}.
Methods and provenance:
{provenance}
"""
from __future__ import annotations
'''

URL_CANON = '''
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

# Query keys that only track the referrer; dropping them does not change the page.
TRACKING_PREFIXES = ("utm_",)
TRACKING_KEYS = {{"fbclid", "gclid", "spm", "from", "share_source", "ref", "mc_cid", "mc_eid",
                 "li_fat_id", "isappinstalled"}}


def canonical_url(url):
    """Normalise case, scheme, ``www.``, default port, trailing slash and
    fragment; drop tracking parameters and sort the rest."""
    parts = urlsplit(url.strip())
    host = (parts.hostname or "").lower()
    if host.startswith("www."):
        host = host[4:]
    if parts.port and parts.port not in (80, 443):
        host = "%s:%d" % (host, parts.port)
    path = parts.path or "/"
    if len(path) > 1 and path.endswith("/"):
        path = path[:-1]
    query = sorted((k, v) for k, v in parse_qsl(parts.query, keep_blank_values=True)
                   if not k.lower().startswith(TRACKING_PREFIXES) and k.lower() not in TRACKING_KEYS)
    return urlunsplit(("https", host, path, urlencode(query), ""))
'''

SHINGLES = '''

import re

THRESHOLD = {threshold}
SHINGLE_K = {k}
_PUNCT = re.compile(r"[\\s\\W_]+", re.UNICODE)


def _normalise(text):
    return _PUNCT.sub("", text.lower())


def shingles(text, k=SHINGLE_K):
    """Character k-grams. Characters (not words) so Chinese text without
    spaces is handled the same way as English."""
    s = _normalise(text)
    if len(s) <= k:
        return {{s}} if s else set()
    return {{s[i:i + k] for i in range(len(s) - k + 1)}}


def jaccard(a, b):
    if not a or not b:
        return 0.0
    return len(a & b) / float(len(a | b))
'''

TITLE_TOKENS = '''

import re

THRESHOLD = {threshold}
_TOKEN = re.compile(r"[a-z0-9]+|[\\u4e00-\\u9fff]", re.UNICODE)


def title_tokens(title):
    return set(_TOKEN.findall(title.lower()))


def jaccard(a, b):
    if not a or not b:
        return 0.0
    return len(a & b) / float(len(a | b))
'''

DEDUP_HEAD = '''

def dedup(items):
    decisions = []
    kept = []          # (id, signature) of items kept so far
    by_url = {}
    for item in items:
        iid = item["id"]
'''

DEDUP_URL_EXACT = '''        url_key = item.get("url", "")
'''

DEDUP_URL_CANON = '''        url_key = canonical_url(item.get("url", ""))
'''

DEDUP_URL_CHECK = '''        if url_key in by_url:
            decisions.append({"id": iid, "duplicate_of": by_url[url_key], "reason": "same-url"})
            continue
'''

DEDUP_SHINGLE_CHECK = '''        sig = shingles(item.get("title", "") + " " + item.get("text", ""))
        best_id, best = None, 0.0
        for kid, ksig in kept:
            score = jaccard(sig, ksig)
            if score > best:
                best_id, best = kid, score
        if best_id is not None and best >= THRESHOLD:
            decisions.append({"id": iid, "duplicate_of": best_id, "reason": "near-dup %.2f" % best})
            continue
'''

DEDUP_TITLE_CHECK = '''        sig = title_tokens(item.get("title", ""))
        best_id, best = None, 0.0
        for kid, ksig in kept:
            score = jaccard(sig, ksig)
            if score > best:
                best_id, best = kid, score
        if best_id is not None and best >= THRESHOLD:
            decisions.append({"id": iid, "duplicate_of": best_id, "reason": "title-overlap %.2f" % best})
            continue
'''

DEDUP_TAIL_SIG = '''        kept.append((iid, sig))
'''

DEDUP_TAIL = '''        by_url[url_key] = iid
        decisions.append({"id": iid, "duplicate_of": None, "reason": "kept"})
    return decisions
'''

KNOWN_METHODS = ("url_canonicalization", "shingle_jaccard", "title_token_overlap")


def render_dedup(methods, params, run_id, variant, provenance, generator="TemplateExecutor"):
    unknown = [m for m in methods if m not in KNOWN_METHODS]
    if unknown:
        raise ValueError("no template for methods: %s" % unknown)
    if "shingle_jaccard" in methods and "title_token_overlap" in methods:
        raise ValueError("shingle_jaccard and title_token_overlap are alternatives")
    prov = "\n".join("  - " + line for line in provenance) or "  - (none)"
    src = HEADER.format(generator=generator, run_id=run_id, variant=variant, provenance=prov)
    if "url_canonicalization" in methods:
        src += URL_CANON.format()
    if "shingle_jaccard" in methods:
        src += SHINGLES.format(threshold=float(params.get("threshold", 0.6)), k=int(params.get("k", 4)))
    if "title_token_overlap" in methods:
        src += TITLE_TOKENS.format(threshold=float(params.get("threshold", 0.3)))
    src += DEDUP_HEAD
    src += DEDUP_URL_CANON if "url_canonicalization" in methods else DEDUP_URL_EXACT
    src += DEDUP_URL_CHECK
    if "shingle_jaccard" in methods:
        src += DEDUP_SHINGLE_CHECK + DEDUP_TAIL_SIG
    elif "title_token_overlap" in methods:
        src += DEDUP_TITLE_CHECK + DEDUP_TAIL_SIG
    src += DEDUP_TAIL
    return src
